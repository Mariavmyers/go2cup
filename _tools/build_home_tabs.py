#!/usr/bin/env python3
"""Write the homepage sport tabs (between the SPORTS TABS markers in index.html).

    python3 _tools/build_home_tabs.py

Each tab shows that sport's next event, read from the same data files as the sport pages.
"""
import json
import os
import re
import sys
from datetime import date, datetime
from html import escape
from zoneinfo import ZoneInfo

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sports_nav import SPORTS  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TODAY = date(2026, 10, 22)
MON = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
NAMES = {"KC": "Chiefs", "SEA": "Seahawks", "DEN": "Broncos", "NYJ": "Jets", "ATL": "Falcons", "ARI": "Cardinals",
         "BUF": "Bills", "LAR": "Rams", "CIN": "Bengals", "NE": "Patriots", "SF": "49ers", "LAC": "Chargers", "LV": "Raiders"}


def e(s):
    return escape(str(s), quote=True)


def d(iso):
    y, m, dd = (int(x) for x in iso[:10].split("-"))
    return date(y, m, dd)


def next_for(slug):
    if slug == "nfl":
        g = sorted([g for g in json.load(open(os.path.join(ROOT, "data", "nfl-2026-schedule.json")))["games"]
                    if "KC" in (g["home"], g["away"]) and not g["played"] and not g["kickoffTBD"]], key=lambda g: g["kickoff"])[0]
        k = datetime.fromisoformat(g["kickoff"].replace("Z", "+00:00")).astimezone(ZoneInfo("America/Chicago"))
        opp = g["away"] if g["home"] == "KC" else g["home"]
        return "%s %d" % (MON[k.month - 1], k.day), "Chiefs %s %s" % ("vs" if g["home"] == "KC" else "at", NAMES.get(opp, opp)), "All 32 teams · Super Bowl LXI travel"
    D = json.load(open(os.path.join(ROOT, "data", "sports", slug + ".json")))
    items = sorted([it for s in D["sections"] for it in s["items"] if d(it.get("end", it["date"])) >= TODAY], key=lambda it: it["date"])
    it = items[0]
    a = d(it["date"])
    return "%s %d" % (MON[a.month - 1], a.day), it["title"], D["title"]


TAB_SUB = {"nfl": "NFL 2026 Season Hub", "nba": "Season hub", "soccer": "MLS · NWSL",
           "ufc": "Fight calendar", "boxing": "Fight calendar", "tennis": "Season finale", "racing": "Formula 1"}

cards = []
for page, label, color, bg in SPORTS:
    slug = page[:-5]
    when, title, _ = next_for(slug)
    cards.append(
        '<a class="sx-tab" href="/%s" style="--sc:%s;--sb:%s">'
        '<span class="sx-name">%s</span><span class="sx-sub">%s</span>'
        '<span class="sx-next"><b>%s</b>%s</span><span class="sx-go">Open &rarr;</span></a>'
        % (page, color, bg, e(label), e(TAB_SUB[slug]), e(when), e(title)))

block = """<!-- SPORTS TABS (generated by _tools/build_home_tabs.py) -->
<section class="sx" aria-labelledby="sx-h">
  <style>
    .sx{background:linear-gradient(180deg,#05080d,#020617);padding:34px 18px 38px;border-bottom:1px solid rgba(255,255,255,.06)}
    .sx-in{max-width:1200px;margin:0 auto}
    .sx h2{font-family:'Bebas Neue',sans-serif;font-size:clamp(2rem,4.5vw,3.2rem);letter-spacing:1px;color:#fff;line-height:1;margin:0}
    .sx p.sx-lead{font-family:'Inter',sans-serif;color:#9fb0ab;font-size:15px;margin:6px 0 18px}
    .sx-grid{display:grid;grid-template-columns:repeat(7,minmax(0,1fr));gap:10px}
    .sx-tab{position:relative;display:flex;flex-direction:column;gap:4px;min-height:190px;padding:16px 14px 14px;border-radius:14px;text-decoration:none;color:#fff;
      background:radial-gradient(120% 90% at 0% 0%,color-mix(in srgb,var(--sc) 22%,transparent),transparent 60%),var(--sb);
      border:1px solid rgba(255,255,255,.08);border-top:4px solid var(--sc);transition:transform .2s,box-shadow .2s,border-color .2s}
    .sx-tab:hover,.sx-tab:focus-visible{transform:translateY(-3px);box-shadow:0 10px 30px -10px var(--sc);border-color:var(--sc);outline:none}
    .sx-name{font-family:'Bebas Neue',sans-serif;font-size:2.1rem;letter-spacing:1px;line-height:.95;color:#fff}
    .sx-sub{font-family:'Oswald',sans-serif;font-size:.78rem;letter-spacing:.08em;text-transform:uppercase;color:var(--sc)}
    .sx-next{font-family:'Inter',sans-serif;font-size:.82rem;line-height:1.35;color:#c9d2cf;margin-top:auto}
    .sx-next b{display:block;font-family:'Oswald',sans-serif;font-weight:600;font-size:.78rem;letter-spacing:.06em;text-transform:uppercase;color:#fff;margin-bottom:2px}
    .sx-go{font-family:'Oswald',sans-serif;font-size:.8rem;letter-spacing:.06em;color:var(--sc);margin-top:6px}
    @media(max-width:1100px){.sx-grid{grid-template-columns:repeat(4,minmax(0,1fr))}}
    @media(max-width:640px){.sx-grid{grid-template-columns:repeat(2,minmax(0,1fr))}.sx-tab{min-height:160px}.sx-name{font-size:1.8rem}}
  </style>
  <div class="sx-in">
    <h2 id="sx-h">Pick your sport</h2>
    <p class="sx-lead">Schedules, big events and travel for every sport we cover, starting from Kansas City.</p>
    <div class="sx-grid">
      %s
    </div>
  </div>
</section>
<!-- /SPORTS TABS -->""".replace("%s", "\n      ".join(cards))

p = os.path.join(ROOT, "index.html")
s = open(p, encoding="utf-8").read()
if "<!-- SPORTS TABS" in s:
    s = re.sub(r"<!-- SPORTS TABS.*?<!-- /SPORTS TABS -->", lambda m: block, s, flags=re.S)
else:
    anchor = "<!-- BRAZIL 2027 HERO + NEXT EVENTS -->"
    assert s.count(anchor) == 1
    s = s.replace(anchor, block + "\n" + anchor)
open(p, "w", encoding="utf-8").write(s)
print("homepage tabs written:", len(cards))
